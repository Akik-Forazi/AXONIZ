/**
 * v2 artifacts — generate markdown summaries after workflow runs.
 *
 * After a workflow completes, this module generates a task-list-style
 * markdown artifact that summarizes what happened:
 * - Workflow name + trigger
 * - Each step: status, duration, tool, result preview
 * - Overall status + total duration
 *
 * Stored at ~/.axoniz/projects/:id/artifacts/:runId.md
 * API: GET /api/axoniz/v2/runs/:id/artifact
 */
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import type { WorkflowRun } from "./v2-schemas";
import { getRun, listWorkflows } from "./v2-workflows";
import { getRecentLogs } from "./v2-workflows";

/** Generate a markdown artifact for a completed workflow run. */
export function generateArtifact(run: WorkflowRun): string {
  const wf = listWorkflows().find(w => w.name === run.workflowId);
  const lines: string[] = [];

  lines.push(`# Workflow: ${run.workflowId}`);
  lines.push("");
  lines.push(`| Field | Value |`);
  lines.push(`|---|---|`);
  lines.push(`| Run ID | ${run.id} |`);
  lines.push(`| Status | ${run.status} |`);
  lines.push(`| Trigger | ${run.trigger} |`);
  lines.push(`| Started | ${new Date(run.startedAt).toLocaleString()} |`);
  lines.push(`| Ended | ${run.endedAt ? new Date(run.endedAt).toLocaleString() : "—" } |`);
  lines.push(`| Duration | ${run.endedAt ? `${((run.endedAt - run.startedAt) / 1000).toFixed(1)}s` : "—" } |`);
  lines.push(`| Steps | ${run.stepsCompleted}/${run.stepsTotal} |`);
  if (run.error) lines.push(`| Error | ${run.error} |`);
  if (wf?.projectId) lines.push(`| Project | ${wf.projectId} |`);
  lines.push("");

  // Step details from logs
  const logs = getRecentLogs(200).filter(l => l.runId === run.id);
  if (logs.length > 0) {
    lines.push(`## Steps`);
    lines.push("");
    lines.push(`| Step | Tool | Event | Duration | Message |`);
    lines.push(`|---|---|---|---|---|`);
    for (const log of logs) {
      if (log.event === "step_start" || log.event === "step_end" || log.event === "step_error") {
        const stepId = log.stepId ?? "—";
        const tool = log.tool ?? "—";
        const dur = log.durationMs ? `${log.durationMs}ms` : "—";
        const msg = log.message.slice(0, 60);
        lines.push(`| ${stepId} | ${tool} | ${log.event} | ${dur} | ${msg} |`);
      }
    }
    lines.push("");
  }

  // Error details
  if (run.error) {
    lines.push(`## Error Details`);
    lines.push("");
    lines.push("```");
    lines.push(run.error);
    lines.push("```");
    lines.push("");
  }

  lines.push(`---`);
  lines.push(`*Generated by AXONIZ v2 at ${new Date().toISOString()}*`);

  return lines.join("\n");
}

/** Save an artifact to disk. */
export function saveArtifact(run: WorkflowRun): string | null {
  try {
    const markdown = generateArtifact(run);
    const dir = run.projectId
      ? path.join(os.homedir(), ".axoniz", "projects", run.projectId, "artifacts")
      : path.join(os.homedir(), ".axoniz", "artifacts");
    fs.mkdirSync(dir, { recursive: true });
    const filePath = path.join(dir, `${run.id}.md`);
    fs.writeFileSync(filePath, markdown, "utf-8");
    return filePath;
  } catch (e) {
    console.warn("[artifacts] save failed:", e instanceof Error ? e.message : String(e));
    return null;
  }
}

/** Get an artifact by run ID. */
export function getArtifact(runId: string): string | null {
  const run = getRun(runId);
  if (!run) return null;
  const dir = run.projectId
    ? path.join(os.homedir(), ".axoniz", "projects", run.projectId, "artifacts")
    : path.join(os.homedir(), ".axoniz", "artifacts");
  const filePath = path.join(dir, `${runId}.md`);
  if (!fs.existsSync(filePath)) {
    // Generate on-demand if not saved
    const markdown = generateArtifact(run);
    return markdown;
  }
  return fs.readFileSync(filePath, "utf-8");
}
